#!/usr/bin/env python3
"""Derive src/models/tmp-model-guide.slim.json — the catalog the FRONTEND bundles.

WHY THIS EXISTS
---------------
`src/models/tmp-model-guide.json` is the generated Model Guide catalog (its
generator, `expand_catalog.py`, lives outside this repo). It carries every field the
extraction produced, and the Rust side embeds it whole (`include_str!` in
`src-tauri/src/probe_api/scene_jobs.rs`, which reads `block_id` + `category`). The
frontend needs far less: `catalog.ts` reads only the fields in `KEEP` below. The rest
was dead weight parsed on every app start, including `image` — 361 vendor PNG tile
paths that nothing renders (block art is original SVG; the Fender photo tiles are
not bundled, and must not come back).

So the full guide stays the source of truth (and Rust's input), and this script
projects it, deterministically, onto the fields the frontend reads. Same rows, same
order, same values — only the unread keys are dropped.

WHEN TO RUN
-----------
After ANY change to tmp-model-guide.json — a catalog regen, or
`scripts/extract_strip_names.py`:

    python3 scripts/slim_model_guide.py
    bun run test

`src/__tests__/models-catalog.test.tsx` fails if the slim file has drifted from the
full guide (a row, an order or a value that differs), so a forgotten re-run is
caught by the gates rather than shipping a stale catalog.

ADDING A FIELD
--------------
If `catalog.ts`'s `RawBlock` starts reading a new field, add it to `KEEP` and re-run.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FULL = os.path.join(ROOT, "src", "models", "tmp-model-guide.json")
SLIM = os.path.join(ROOT, "src", "models", "tmp-model-guide.slim.json")

# The `blocks[]` fields `src/models/catalog.ts` (`RawBlock`) reads — in source order.
KEEP = (
    "block_id",
    "block_name",
    "strip_name",
    "available",
    "since",
    "catalog_id",
    "real_unit",
    "category",
    "subcategory",
    "effect_type",
    "form",
    "channels",
    "convolution",
)

NOTE = (
    "GENERATED by scripts/slim_model_guide.py from tmp-model-guide.json - do not "
    "hand-edit. Only the blocks[] fields the frontend reads; re-run after any change "
    "to the full guide."
)


def main() -> None:
    with open(FULL, encoding="utf-8") as f:
        guide = json.load(f)
    blocks = [
        {k: row[k] for k in KEEP if k in row}
        for row in guide["blocks"]
    ]
    slim = {"generated": NOTE, "blocks": blocks}
    with open(SLIM, "w", encoding="utf-8") as f:
        json.dump(slim, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(
        f"wrote {os.path.relpath(SLIM, ROOT)}: {len(blocks)} rows, "
        f"{os.path.getsize(SLIM)} bytes (full guide {os.path.getsize(FULL)} bytes)"
    )


if __name__ == "__main__":
    main()
