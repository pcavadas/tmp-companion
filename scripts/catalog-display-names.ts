#!/usr/bin/env bun
// scripts/catalog-display-names.ts — generates src/models/model-display-names.json, the
// ONE mapping from each catalog model's name as the unit prints it ("FENDER '57 DELUXE")
// to the name the app shows ("Fender '57 Deluxe").
//
// Usage (from the repo root):  bun scripts/catalog-display-names.ts
// Re-run it after any change to the catalog (tmp-model-guide.slim.json): the Vitest
// gate in src/__tests__/catalogDisplayNames.test.ts fails when a model has no mapping
// or when this file and the generated JSON disagree. Never hand-edit the JSON; change
// the rules or the KEEP list here and re-run.
//
// The rules, per name:
//  - A name that already has a lowercase letter is in normal case on the unit
//    ("'57 Champ", "1x12 EVH 5150 G12H"): it is kept exactly as it is.
//  - Otherwise each word is recased on its own, and a word joined by "-", "/", "+" or
//    parentheses is recased part by part ("VIBRO-KING" → "Vibro-King"):
//      · a word in KEEP takes KEEP's spelling (real acronyms, a roman numeral, the
//        unit's own "Ch1");
//      · a cabinet size keeps a lowercase x ("4X12" → "4x12"), as the unit prints it;
//      · a decade keeps a lowercase s ("'70S" → "'70s");
//      · a word with a digit is a model number and stays as printed ("5150IIIS", "6L6",
//        "V30", "SM57", "50W", "'57");
//      · any other word gets a capital and lowercase ("DELUXE" → "Deluxe").
// So the mapping only ever changes letter case: the test pins that, too.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** All-caps words that keep a spelling of their own (checked before every other rule).
 *  Any other word without a digit gets a capital and lowercase, so a new acronym in a
 *  catalog regen must be added here (the script prints every short word it recased, to
 *  review). */
export const KEEP: Readonly<Record<string, string>> = {
  // brands and makers
  EVH: "EVH",
  SWR: "SWR",
  // model and part acronyms
  CSD: "CSD", // Comic Sans Drive
  CS: "CS", // a Princeton speaker code
  EQ: "EQ",
  EV: "EV", // Electro-Voice speaker
  FBE: "FBE", // FBE-100
  FX: "FX", // the utility blocks (no all-caps name carries it today)
  IR: "IR", // the utility blocks (no all-caps name carries it today)
  JC: "JC", // Jazz Chorus
  LTD: "LTD",
  NBC: "NBC", // no bright cap
  OD: "OD", // overdrive
  SDD: "SDD", // SDD-3000
  TV: "TV", // Bassman TV
  UK: "UK",
  XO: "XO",
  // a roman numeral
  II: "II",
  // channel numbers, as the unit's own scribble strip spells them ("Marksman Ch1")
  CH1: "Ch1",
  CH2: "Ch2",
};

const CAB_SIZE = /^\d+X\d+$/;
const DECADE = /^'\d0S$/;
const HAS_DIGIT = /\d/;
const HAS_LOWER = /[a-z]/;

/** Recase one word part (no separators inside). */
function recasePart(part: string, recased: Set<string>): string {
  if (part === "") return part;
  const keep = KEEP[part] as string | undefined;
  if (keep !== undefined) return keep;
  if (CAB_SIZE.test(part)) return part.toLowerCase();
  if (DECADE.test(part)) return part.slice(0, -1) + "s";
  if (HAS_DIGIT.test(part)) return part;
  if (!/[A-Z]/.test(part)) return part;
  if (part.length <= 3) recased.add(part);
  return part.charAt(0) + part.slice(1).toLowerCase();
}

/** The display name for one catalog name. `recased` collects the short words it
 *  title-cased, for the maintainer to review. */
export function normalCase(raw: string, recased = new Set<string>()): string {
  if (HAS_LOWER.test(raw)) return raw;
  // Split on the separators, keeping them, and recase the parts between.
  return raw
    .split(/([\s\-/+()])/)
    .map((part, i) => (i % 2 === 1 ? part : recasePart(part, recased)))
    .join("");
}

interface GuideRow {
  block_name: string;
  available: boolean;
}

/** The mapping for every AVAILABLE catalog row (the rows the app shows), keyed by the
 *  name as the unit prints it, in the catalog's order. */
export function buildDisplayNames(
  rows: readonly GuideRow[],
  recased = new Set<string>(),
): Record<string, string> {
  const names: Record<string, string> = {};
  for (const r of rows) {
    if (!r.available || r.block_name in names) continue;
    names[r.block_name] = normalCase(r.block_name, recased);
  }
  return names;
}

export const GENERATED_NOTE =
  "GENERATED by scripts/catalog-display-names.ts from tmp-model-guide.slim.json - do not hand-edit. Re-run `bun scripts/catalog-display-names.ts` after any change to the catalog.";

function main(): void {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const guidePath = resolve(root, "src/models/tmp-model-guide.slim.json");
  const outPath = resolve(root, "src/models/model-display-names.json");
  const guide = JSON.parse(readFileSync(guidePath, "utf8")) as {
    blocks: GuideRow[];
  };
  const recased = new Set<string>();
  const names = buildDisplayNames(guide.blocks, recased);
  const out = { generated: GENERATED_NOTE, names };
  writeFileSync(outPath, JSON.stringify(out, null, 2) + "\n");
  console.log(
    `wrote ${String(Object.keys(names).length)} names to ${outPath}\n` +
      `short words recased (check none is an acronym): ${[...recased].sort().join(", ")}`,
  );
}

// Run only when executed directly (the Vitest gate imports the functions above).
if (
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
